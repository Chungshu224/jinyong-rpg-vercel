// ---------- 每日簽到 ----------
// 以台灣時區（UTC+8）判斷「今天」，連續簽到以 7 天為一輪，獎勵遞增，第 7 天有額外大獎
function 台灣日期字串(date) {
  const 偏移毫秒 = 8 * 60 * 60 * 1000;
  return new Date(date.getTime() + 偏移毫秒).toISOString().slice(0, 10);
}

const 簽到獎勵表 = [
  { 銀兩: 20 },
  { 銀兩: 30, 內力: 5 },
  { 銀兩: 40, 外功: 5 },
  { 銀兩: 50, 強化石: 2 },
  { 銀兩: 70, 內力: 10, 外功: 10 },
  { 銀兩: 90, 強化石: 3 },
  { 銀兩: 150, 內力: 20, 外功: 20, 強化石: 5 },
];

function 簽到(c) {
  if (!c.簽到記錄) c.簽到記錄 = { 最後簽到日期: null, 連續天數: 0 };

  const 今天 = 台灣日期字串(new Date());
  if (c.簽到記錄.最後簽到日期 === 今天) {
    return `你今天已經簽到過了，明天再來吧！（連續簽到 ${c.簽到記錄.連續天數} 天）`;
  }

  const 昨天 = 台灣日期字串(new Date(Date.now() - 86400000));
  if (c.簽到記錄.最後簽到日期 === 昨天) {
    c.簽到記錄.連續天數 += 1;
  } else {
    c.簽到記錄.連續天數 = 1;
  }
  c.簽到記錄.最後簽到日期 = 今天;

  const 輪內天數 = ((c.簽到記錄.連續天數 - 1) % 7) + 1;
  const 獎勵 = 簽到獎勵表[輪內天數 - 1];

  const 說明 = [];
  c.銀兩 += 獎勵.銀兩;
  說明.push(`銀兩 +${獎勵.銀兩}`);
  if (獎勵.內力) { c.內力 += 獎勵.內力; 說明.push(`內力 +${獎勵.內力}`); }
  if (獎勵.外功) { c.外功 += 獎勵.外功; 說明.push(`外功經驗 +${獎勵.外功}`); }
  if (獎勵.強化石) { c.強化石 = (c.強化石 || 0) + 獎勵.強化石; 說明.push(`強化石 +${獎勵.強化石}`); }

  const 行 = [
    `簽到成功！（連續第 ${c.簽到記錄.連續天數} 天，本輪第 ${輪內天數}/7 天）`,
    `（${說明.join('，')}）`,
  ];
  if (輪內天數 === 7) 行.push('【七日全勤】獎勵格外豐厚，明日起將開啟新一輪簽到！');
  行.push(...檢查突破(c));
  return 行.join('\n');
}

