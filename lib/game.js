function 兵器類型(招式名稱) {
  return 招式類型對照表[招式名稱] || '拳';
}

// 攻方類型對守方類型的效力係數：克制 1.15、被克制 0.85、其餘 1.0
function 類型加成係數(攻方類型, 守方類型) {
  const iA = 兵器順序.indexOf(攻方類型);
  const iB = 兵器順序.indexOf(守方類型);
  if (iA === -1 || iB === -1 || iA === iB) return 1;
  if ((iA + 1) % 兵器順序.length === iB) return 1.15;
  if ((iB + 1) % 兵器順序.length === iA) return 0.85;
  return 1;
}

// 依克制關係回傳一句戰鬥旁白（無克制關係則回傳空字串）
function 類型關係文字(攻方類型, 守方類型) {
  const 係數 = 類型加成係數(攻方類型, 守方類型);
  if (係數 > 1) return `（你的「${攻方類型}」法克制對方「${守方類型}」路數，出招格外犀利！）`;
  if (係數 < 1) return `（對方「${守方類型}」路數克制你的「${攻方類型}」法，這場交手格外艱難。）`;
  return '';
}

