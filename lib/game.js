// 取得某裝備欄位「基礎」加成（不含強化/套裝，0 表示未裝備該欄位）
function 裝備基礎加成(c, 欄位) {
  const 名稱 = (c.裝備 || {})[欄位];
  if (!名稱) return 0;
  const item = (裝備清單[欄位] || []).find((i) => i.名稱 === 名稱);
  return item ? item.加成 : 0;
}

// 取得某裝備欄位目前的強化等級加成（每級 +5%）
function 裝備強化加成(c, 欄位) {
  const 名稱 = (c.裝備 || {})[欄位];
  if (!名稱) return 0;
  const 等級 = (c.裝備強化 || {})[名稱] || 0;
  return 等級 * 0.05;
}

// 套裝加成：三個欄位裝備的物品剛好組成同一套裝時生效
function 套裝加成(c) {
  const 裝備 = c.裝備 || {};
  for (const 套裝 of 套裝清單) {
    const [武, 防, 飾] = 套裝.物品;
    if (裝備.武器 === 武 && 裝備.防具 === 防 && 裝備.飾品 === 飾) {
      return 套裝.加成;
    }
  }
  return 0;
}

// 轉世加成：每次歸隱重出江湖後永久疊加的修練效率加成（每次 +10%）
function 轉世加成(c) {
  return (c.轉世次數 || 0) * 0.10;
}

// 取得目前生效的套裝名稱（若有）
function 套裝名稱(c) {
  const 裝備 = c.裝備 || {};
  for (const 套裝 of 套裝清單) {
    const [武, 防, 飾] = 套裝.物品;
    if (裝備.武器 === 武 && 裝備.防具 === 防 && 裝備.飾品 === 飾) {
      return 套裝.名稱;
    }
  }
  return null;
}

// 某裝備欄位的總加成 = 基礎加成 + 強化加成 + 套裝加成 + 轉世加成
function 裝備加成(c, 欄位) {
  return 裝備基礎加成(c, 欄位) + 裝備強化加成(c, 欄位) + 套裝加成(c) + 轉世加成(c);
}

// 合併「通用」與「已加入門派的專屬」與「已合成秘笈」武學表
function 全部心法(c) {
  const merged = { ...心法通用 };
  if (c.門派 && 門派清單[c.門派]) {
    const s = 門派清單[c.門派].心法;
    merged[s.名稱] = { 內功倍率: s.內功倍率, 門檻: s.門檻, 門檻類型: '門派聲望' };
  }
  for (const 秘笈 of 秘笈清單) {
    if (秘笈.類型 === '心法' && (c.已習秘笈 || []).includes(秘笈.名稱)) {
      merged[秘笈.名稱] = { 內功倍率: 秘笈.倍率, 門檻: 0, 門檻類型: '內力' };
    }
  }
  return merged;
}

function 全部招式(c) {
  const merged = { ...外功通用 };
  if (c.門派 && 門派清單[c.門派]) {
    const s = 門派清單[c.門派].招式;
    merged[s.名稱] = { 外功倍率: s.外功倍率, 門檻: s.門檻, 門檻類型: '門派聲望' };
  }
  for (const 秘笈 of 秘笈清單) {
    if (秘笈.類型 === '招式' && (c.已習秘笈 || []).includes(秘笈.名稱)) {
      merged[秘笈.名稱] = { 外功倍率: 秘笈.倍率, 門檻: 0, 門檻類型: '外功' };
    }
  }
  return merged;
}

// 離線掛機結算
function 結算離線進度(c) {
  const 現在 = Date.now();
  const 經過分鐘 = Math.floor((現在 - c.最後上線) / 60000);
  if (經過分鐘 <= 0) return null;

  const 有效分鐘 = Math.min(經過分鐘, 480);
  const 心法表 = 全部心法(c);
  const 招式表 = 全部招式(c);
  const 心法倍率 = (心法表[c.心法]?.內功倍率 ?? 1.0) * (1 + 裝備加成(c, '防具'));
  const 招式倍率 = (招式表[c.招式]?.外功倍率 ?? 1.0) * (1 + 裝備加成(c, '武器'));

  const 內力獲得 = Math.floor(有效分鐘 * 0.3 * 心法倍率);
  const 外功獲得 = Math.floor(有效分鐘 * 0.2 * 招式倍率);

  c.內力 += 內力獲得;
  c.外功 += 外功獲得;
  c.最後上線 = 現在;

  if (內力獲得 === 0 && 外功獲得 === 0) return null;
  return `（離線 ${經過分鐘} 分鐘，自動修練：內力 +${內力獲得}，外功經驗 +${外功獲得}）`;
}

