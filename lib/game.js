function 購買或裝備(c, 名稱) {
  if (!c.裝備) c.裝備 = {};
  if (!c.已購裝備) c.已購裝備 = [];
  if (!c.裝備詞綴) c.裝備詞綴 = {};

  for (const [欄位, items] of Object.entries(裝備清單)) {
    const item = items.find((i) => i.名稱 === 名稱);
    if (!item) continue;

    if (c.已購裝備.includes(名稱)) {
      if (c.裝備[欄位] === 名稱) {
        return `你已裝備著「${名稱}」了。`;
      }
      c.裝備[欄位] = 名稱;
      const 詞綴文字 = c.裝備詞綴[名稱] && c.裝備詞綴[名稱] !== '凡品' ? `【${c.裝備詞綴[名稱]}】` : '';
      return `已裝備${詞綴文字}「${名稱}」！（${item.說明}）`;
    }

    if (c.銀兩 < item.售價) {
      return `銀兩不足，「${名稱}」需要 ${item.售價} 銀兩，你目前只有 ${c.銀兩} 銀兩。`;
    }

    c.銀兩 -= item.售價;
    c.已購裝備.push(名稱);
    c.裝備[欄位] = 名稱;
    const 詞綴 = 抽取詞綴();
    c.裝備詞綴[名稱] = 詞綴;
    const 詞綴說明 = 詞綴 === '凡品' ? '' : `\n【品質：${詞綴}】額外加成 +${Math.round((詞綴清單.find((d) => d.名稱 === 詞綴).加成) * 100)}%！`;
    return `花費 ${item.售價} 銀兩購入並裝備「${名稱}」！（${item.說明}）${詞綴說明}`;
  }

  return `藏寶閣中沒有「${名稱}」這件裝備。`;
}

