// ---------- 行動力系統 ----------
// 每個主動行動消耗行動力，每 15 分鐘恢復 1 點，讓遊戲步調跟著時間走而非手速；
// 藥鋪丹藥、藏寶閣、強化坊、合成、簽到、轉世、查詢類動作不消耗行動力。
const 行動力上限基礎 = 20;
const 行動力恢復間隔分鐘 = 15;

function 行動力上限(c) {
  return 行動力上限基礎 + (c.轉世次數 || 0) * 2;
}

// 護膝提供的行動力恢復加速（分鐘），下限保留 5 分鐘避免完全失衡；強化等級與詞綴品質皆按比例納入計算
function 護膝加成分鐘(c) {
  const 名稱 = (c.裝備 || {}).護膝;
  if (!名稱) return 0;
  const item = (裝備清單.護膝 || []).find((i) => i.名稱 === 名稱);
  if (!item) return 0;
  const 等級 = (c.裝備強化 || {})[名稱] || 0;
  const 詞綴加成 = 裝備詞綴加成(c, '護膝');
  return item.加成分鐘 * (1 + 詞綴加成) + 等級 * 0.5;
}

function 有效恢復間隔分鐘(c) {
  return Math.max(5, 行動力恢復間隔分鐘 - 護膝加成分鐘(c));
}

// 依經過時間同步恢復行動力（會直接修改 c，呼叫端記得存檔）
function 同步行動力(c) {
  if (c.行動力 === undefined || c.行動力 === null) c.行動力 = 行動力上限(c);
  if (!c.行動力最後更新) c.行動力最後更新 = Date.now();

  const 上限 = 行動力上限(c);
  if (c.行動力 >= 上限) {
    c.行動力最後更新 = Date.now();
    return;
  }

  const 間隔毫秒 = 有效恢復間隔分鐘(c) * 60000;
  const 經過格數 = Math.floor((Date.now() - c.行動力最後更新) / 間隔毫秒);
  if (經過格數 > 0) {
    c.行動力 = Math.min(上限, c.行動力 + 經過格數);
    c.行動力最後更新 += 經過格數 * 間隔毫秒;
  }
}

// 嘗試消耗行動力；足夠則扣除並回傳 null，不足則回傳提示文字（不扣除）
function 消耗行動力(c, 花費) {
  同步行動力(c);
  const 上限 = 行動力上限(c);
  if (c.行動力 < 花費) {
    const 間隔分鐘 = 有效恢復間隔分鐘(c);
    const 已過毫秒 = Date.now() - c.行動力最後更新;
    const 剩餘分鐘 = Math.max(1, Math.ceil((間隔分鐘 * 60000 - 已過毫秒) / 60000));
    return `行動力不足（${c.行動力}/${上限}），約 ${剩餘分鐘} 分鐘後恢復 1 點。可以先逛「藏寶閣」「強化坊」「合成」「藥鋪」「簽到」，這些都不耗行動力。`;
  }
  c.行動力 -= 花費;
  return null;
}

