function 門派清單文字() {
  return Object.entries(門派清單)
    .map(([名稱, 資料]) => `【${名稱}】${資料.簡介}`)
    .join('\n\n');
}

function 拜師(c, 門派名稱) {
  if (c.門派) {
    return `你已是「${c.門派}」${c.門派職位}，一日為徒終生為師，尚無轉投他派之理。`;
  }
  const sect = 門派清單[門派名稱];
  if (!sect) {
    return `江湖上未曾聽聞「${門派名稱}」這個門派，請從清單中選擇。`;
  }
  c.門派 = 門派名稱;
  c.門派聲望 = 0;
  c.門派職位 = '外門弟子';
  return `${sect.簡介}\n\n你正式拜入「${門派名稱}」，成為外門弟子！從今可修練本派武學「${sect.心法.名稱}」與「${sect.招式.名稱}」，並可承接門派任務累積聲望。`;
}

function 門派任務(c) {
  if (!c.門派) {
    return '你尚未拜入任何門派，請先使用「拜師」加入一個門派，才能承接門派任務。';
  }
  const sect = 門派清單[c.門派];
  const 任務 = sect.任務庫[Math.floor(Math.random() * sect.任務庫.length)];
  const 結果 = 任務.effect(c);
  const 行 = [任務.text, `（${結果}）`];

  const 升職訊息 = 更新門派職位(c);
  if (升職訊息) 行.push(升職訊息);

  行.push(...檢查突破(c));
  return 行.join('\n');
}

