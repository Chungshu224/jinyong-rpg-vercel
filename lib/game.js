// 取得某裝備欄位「基礎」加成（不含強化/套裝，0 表示未裝備該欄位）
// 武器另外會檢查兵器類型是否與目前修練招式相符，相符則有 +10% 契合加成
function 裝備基礎加成(c, 欄位) {
  const 名稱 = (c.裝備 || {})[欄位];
  if (!名稱) return 0;
  const item = (裝備清單[欄位] || []).find((i) => i.名稱 === 名稱);
  if (!item) return 0;
  let 加成 = item.加成;
  if (欄位 === '武器' && item.兵器 && item.兵器 === 兵器類型(c.招式)) {
    加成 += 0.10;
  }
  return 加成;
}

// 取得某裝備欄位目前的強化等級加成（每級 +5%）
function 裝備強化加成(c, 欄位) {
  const 名稱 = (c.裝備 || {})[欄位];
  if (!名稱) return 0;
  const 等級 = (c.裝備強化 || {})[名稱] || 0;
  return 等級 * 0.05;
}

// 套裝加成：套裝比對(c) 已在裝備清單定義處算好目前成套狀態，這裡只取加成數值
function 套裝加成(c) {
  const 套 = 套裝比對(c);
  return 套 ? 套.加成 : 0;
}

// 轉世加成：每次歸隱重出江湖後永久疊加的修練效率加成（每次 +10%）
function 轉世加成(c) {
  return (c.轉世次數 || 0) * 0.10;
}

// 傳說加成：完成主線「尋找屠龍刀與倚天劍」全部章回後獲得的永久加成
function 傳說加成(c) {
  return (c.主線進度 || 0) >= 主線章回.length ? 0.15 : 0;
}

// 取得目前生效的套裝名稱與件數說明（若有）
function 套裝名稱(c) {
  const 套 = 套裝比對(c);
  if (!套) return null;
  return 套.件數 > 3 ? `${套.名稱}（${套.件數} 件同階）` : 套.名稱;
}

// 取得某裝備欄位目前的詞綴加成（0 表示未裝備或詞綴為凡品）
function 裝備詞綴加成(c, 欄位) {
  const 名稱 = (c.裝備 || {})[欄位];
  if (!名稱) return 0;
  const 詞綴名稱 = (c.裝備詞綴 || {})[名稱];
  if (!詞綴名稱) return 0;
  const 詞綴 = 詞綴清單.find((d) => d.名稱 === 詞綴名稱);
  return 詞綴 ? 詞綴.加成 : 0;
}

// 某裝備欄位的總加成 = 基礎加成 + 強化加成 + 詞綴加成 + 套裝加成 + 轉世加成 + 傳說加成
function 裝備加成(c, 欄位) {
  return 裝備基礎加成(c, 欄位) + 裝備強化加成(c, 欄位) + 裝備詞綴加成(c, 欄位) + 套裝加成(c) + 轉世加成(c) + 傳說加成(c);
}

// 鞋子提供的戰鬥銀兩收穫加成（比武/切磋/試煉共用）
// 鞋子提供的戰鬥銀兩收穫加成（比武/切磋/試煉共用），強化等級與詞綴品質皆納入計算
function 鞋子銀兩加成(c) {
  const 名稱 = (c.裝備 || {}).鞋子;
  if (!名稱) return 0;
  const item = (裝備清單.鞋子 || []).find((i) => i.名稱 === 名稱);
  if (!item) return 0;
  const 等級 = (c.裝備強化 || {})[名稱] || 0;
  const 詞綴加成 = 裝備詞綴加成(c, '鞋子');
  return item.加成 + 等級 * 0.05 + 詞綴加成;
}

// 合併「通用」與「已加入門派的專屬三階技能樹」與「已合成秘笈」武學表（不篩選門檻，供查詢用）
function 全部心法(c) {
  const merged = { ...心法通用 };
  if (c.門派 && 門派清單[c.門派]) {
    for (const 階 of 門派清單[c.門派].心法樹) {
      merged[階.名稱] = { 內功倍率: 階.內功倍率, 門檻: 階.門檻, 門檻類型: '門派聲望' };
    }
  }
  for (const 秘笈 of 秘笈清單) {
    if (秘笈.類型 === '心法' && (c.已習秘笈 || []).includes(秘笈.名稱)) {
      merged[秘笈.名稱] = { 內功倍率: 秘笈.倍率, 門檻: 0, 門檻類型: '內力' };
    }
  }
  return merged;
}

function 全部招式(c) {
  const merged = { ...外功通用 };
  if (c.門派 && 門派清單[c.門派]) {
    for (const 階 of 門派清單[c.門派].招式樹) {
      merged[階.名稱] = { 外功倍率: 階.外功倍率, 門檻: 階.門檻, 門檻類型: '門派聲望' };
    }
  }
  for (const 秘笈 of 秘笈清單) {
    if (秘笈.類型 === '招式' && (c.已習秘笈 || []).includes(秘笈.名稱)) {
      merged[秘笈.名稱] = { 外功倍率: 秘笈.倍率, 門檻: 0, 門檻類型: '外功' };
    }
  }
  return merged;
}

// 離線掛機結算
function 結算離線進度(c) {
  const 現在 = Date.now();
  const 經過分鐘 = Math.floor((現在 - c.最後上線) / 60000);
  if (經過分鐘 <= 0) return null;

  const 有效分鐘 = Math.min(經過分鐘, 480);
  const 心法表 = 全部心法(c);
  const 招式表 = 全部招式(c);
  const 心法倍率 = (心法表[c.心法]?.內功倍率 ?? 1.0) * (1 + 裝備加成(c, '防具'));
  const 招式倍率 = (招式表[c.招式]?.外功倍率 ?? 1.0) * (1 + 裝備加成(c, '武器'));

  const 內力獲得 = Math.floor(有效分鐘 * 0.3 * 心法倍率);
  const 外功獲得 = Math.floor(有效分鐘 * 0.2 * 招式倍率);

  c.內力 += 內力獲得;
  c.外功 += 外功獲得;
  c.最後上線 = 現在;

  if (內力獲得 === 0 && 外功獲得 === 0) return null;
  return `（離線 ${經過分鐘} 分鐘，自動修練：內力 +${內力獲得}，外功經驗 +${外功獲得}）`;
}

// 依已遇典故數量檢查是否解鎖新的里程碑稱號，回傳新解鎖訊息陣列
function 更新稱號里程碑(c) {
  if (!c.已獲稱號) c.已獲稱號 = [];
  const 訊息 = [];
  const 數量 = (c.已遇典故 || []).length;
  for (const 階 of 稱號里程碑) {
    if (數量 >= 階.門檻 && !c.已獲稱號.includes(階.稱號)) {
      c.已獲稱號.push(階.稱號);
      訊息.push(`【獲得稱號】「${階.稱號}」！`);
    }
  }
  return 訊息;
}

// 依已遇典故數量回傳目前外觀描述（自動變化，不可選擇）
function 外觀描述(c) {
  const 數量 = (c.已遇典故 || []).length;
  let 描述 = 外觀里程碑[0].描述;
  for (const 階 of 外觀里程碑) {
    if (數量 >= 階.門檻) 描述 = 階.描述;
  }
  return 描述;
}

