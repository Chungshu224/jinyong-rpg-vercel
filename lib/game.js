// 以台灣時區（UTC+8）判斷「今天」，連續簽到以 7 天為一輪，獎勵遞增，第 7 天有額外大獎
function 台灣日期字串(date) {
  const 偏移毫秒 = 8 * 60 * 60 * 1000;
  return new Date(date.getTime() + 偏移毫秒).toISOString().slice(0, 10);
}

// ---------- 每日故事配額 ----------
// 主線「探索」與全部「副本」共用同一份每日額度，不管戰力/行動力刷得多快，
// 故事本身一天只能推進固定章數，確保長篇故事線真的能撐住長時間遊玩
const 每日故事配額 = 1;

function 故事配額狀態(c) {
  if (!c.故事配額) c.故事配額 = { 日期: null, 已用: 0 };
  const 今天 = 台灣日期字串(new Date());
  if (c.故事配額.日期 !== 今天) {
    c.故事配額.日期 = 今天;
    c.故事配額.已用 = 0;
  }
  return c.故事配額;
}

// 嘗試消耗一次故事配額；足夠則扣除並回傳 true，不足回傳 false（不扣除）
function 消耗故事配額(c) {
  const 狀態 = 故事配額狀態(c);
  if (狀態.已用 >= 每日故事配額) return false;
  狀態.已用 += 1;
  return true;
}

function 故事配額提示(c) {
  const 狀態 = 故事配額狀態(c);
  return `今日的故事推進次數已用完（每日 ${每日故事配額} 次，主線「探索」與所有「副本」共用額度），明天再繼續閱讀這段江湖傳奇吧！（今日已用 ${狀態.已用}/${每日故事配額}）`;
}

