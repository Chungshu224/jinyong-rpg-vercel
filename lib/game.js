// ---------- 江湖排行榜（跨玩家，依戰力排序） ----------
function 排行榜文字(角色列表, 自己ID) {
  const 排序 = 角色列表
    .map((項) => ({
      chat_id: 項.chat_id,
      名字: (項.data && 項.data.名字) || '無名俠客',
      戰力: 項.data ? 戰力(項.data) : 0,
      轉世次數: (項.data && 項.data.轉世次數) || 0,
    }))
    .sort((a, b) => b.戰力 - a.戰力);

  if (排序.length === 0) return '江湖上尚無其他俠客的記錄。';

  const 前十 = 排序.slice(0, 10);
  const 行 = 前十.map((p, i) => {
    const 轉世文字 = p.轉世次數 > 0 ? `　轉世 ${p.轉世次數} 次` : '';
    return `${i + 1}. ${p.名字}　戰力 ${p.戰力}${轉世文字}`;
  });

  const 自己索引 = 排序.findIndex((p) => String(p.chat_id) === String(自己ID));
  if (自己索引 >= 0) {
    const 自己排名 = 自己索引 + 1;
    if (自己排名 > 10) {
      行.push('', `你目前排名第 ${自己排名} 位（共 ${排序.length} 位俠客）`);
    }
  }

  return 行.join('\n');
}

