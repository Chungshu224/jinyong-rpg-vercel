function 換稱號(c, 稱號名稱) {
  if (稱號名稱 === '無') {
    c.目前稱號 = null;
    return '已卸下稱號。';
  }
  if (!(c.已獲稱號 || []).includes(稱號名稱)) {
    return `你尚未獲得「${稱號名稱}」這個稱號。`;
  }
  c.目前稱號 = 稱號名稱;
  return `已佩戴稱號「${稱號名稱}」！`;
}

function 判定值(c, 門檻類型) {
  if (門檻類型 === '內力') return c.內力;
  if (門檻類型 === '外功') return c.外功;
  if (門檻類型 === '門派聲望') return c.門派聲望;
  return 0;
}

