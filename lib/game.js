function 全部副本名稱() {
  return Object.keys(副本清單);
}

function 副本總覽文字(c) {
  return 全部副本名稱()
    .map((名) => {
      const 章節 = 副本清單[名];
      const 進度 = ((c.副本進度 || {})[名]) || 0;
      const 狀態 = 進度 >= 章節.length ? '已完結' : `進度 ${進度}/${章節.length}`;
      return `【${名}】${狀態}`;
    })
    .join('\n');
}

function 副本清單文字(c, 小說名) {
  const 章節 = 副本清單[小說名];
  if (!章節) return `江湖上未曾聽聞「${小說名}」這部奇書。`;
  const 進度 = ((c.副本進度 || {})[小說名]) || 0;
  return 章節
    .map((章, i) => {
      if (i < 進度) return `✅ ${章.章名}（已完成）`;
      if (i === 進度) return `▶️ ${章.章名}\n${章.敘述}\n（推進條件：${章.條件文字}）`;
      return `🔒 ${章.章名}（尚未解鎖）`;
    })
    .join('\n\n');
}

function 推進副本(c, 小說名) {
  const 章節 = 副本清單[小說名];
  if (!章節) return `江湖上未曾聽聞「${小說名}」這部奇書。`;
  if (!c.副本進度) c.副本進度 = {};
  const 進度 = c.副本進度[小說名] || 0;

  if (進度 >= 章節.length) {
    return `你已經完成「${小說名}」的故事，這段傳奇已成江湖佳話。`;
  }

  const 章 = 章節[進度];
  if (!章.條件(c)) {
    return `${章.章名}\n\n${章.敘述}\n\n（尚未達成推進條件：${章.條件文字}）`;
  }

  if (!消耗故事配額(c)) return 故事配額提示(c);

  c.副本進度[小說名] = 進度 + 1;
  const 獎勵文字 = 章.獎勵(c);
  const 行 = [章.章名, '', 章.敘述, '', `【回目完成】${獎勵文字}`];
  if (c.副本進度[小說名] >= 章節.length) {
    行.push('', `【「${小說名}」完結】這段傳奇故事已寫入你的江湖史冊！`);
  }
  行.push(...檢查突破(c));
  return 行.join('\n');
}

