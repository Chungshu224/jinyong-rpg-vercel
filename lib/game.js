// 找出目前裝備中，同一階數出現最多次的階數與件數（至少需 3 件同階才算成套）
function 套裝比對(c) {
  const 裝備 = c.裝備 || {};
  const items = 套裝欄位順序
    .map((欄) => (裝備清單[欄] || []).find((i) => i.名稱 === 裝備[欄]))
    .filter(Boolean);
  if (items.length < 3) return null;
  const 計數 = {};
  for (const item of items) 計數[item.tier] = (計數[item.tier] || 0) + 1;
  let 最佳階 = null;
  let 最佳件數 = 0;
  for (const [階, 件數] of Object.entries(計數)) {
    if (件數 > 最佳件數) { 最佳件數 = 件數; 最佳階 = Number(階); }
  }
  if (最佳件數 < 3) return null;
  const 基礎套 = 套裝清單.find((s) => s.tier === 最佳階);
  if (!基礎套) return null;
  let 加成 = 基礎套.加成;
  if (最佳件數 >= 4) 加成 += 0.05;
  if (最佳件數 >= 5) 加成 += 0.07;
  return { ...基礎套, 加成, 件數: 最佳件數 };
}

