// 檢查是否有更高倍率的武學可以突破（心法/招式各自取全場最佳）
function 檢查突破(c) {
  const 訊息 = [];

  const 心法表 = 全部心法(c);
  let 目前心法倍率 = 心法表[c.心法]?.內功倍率 ?? 1.0;
  for (const [名稱, 資料] of Object.entries(心法表)) {
    if (判定值(c, 資料.門檻類型) >= 資料.門檻 && 資料.內功倍率 > 目前心法倍率) {
      c.心法 = 名稱;
      目前心法倍率 = 資料.內功倍率;
      訊息.push(`【突破！】修為/門派貢獻俱足，習得「${名稱}」，內力修練效率大幅提升！`);
    }
  }

  const 招式表 = 全部招式(c);
  let 目前招式倍率 = 招式表[c.招式]?.外功倍率 ?? 1.0;
  for (const [名稱, 資料] of Object.entries(招式表)) {
    if (判定值(c, 資料.門檻類型) >= 資料.門檻 && 資料.外功倍率 > 目前招式倍率) {
      c.招式 = 名稱;
      目前招式倍率 = 資料.外功倍率;
      訊息.push(`【突破！】招式融會貫通，習得「${名稱}」！`);
    }
  }

  return 訊息;
}

