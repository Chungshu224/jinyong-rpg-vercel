const 強化上限 = 15;

function 強化坊清單文字(c) {
  const 已購 = c.已購裝備 || [];
  if (已購.length === 0) {
    return '你尚未擁有任何裝備，請先到「藏寶閣」購買。';
  }
  const 行 = [`目前強化石：${c.強化石 || 0}`, ''];
  for (const 名稱 of 已購) {
    const 等級 = (c.裝備強化 || {})[名稱] || 0;
    if (等級 >= 強化上限) {
      行.push(`${名稱}（目前 +${等級}，已達上限）`);
      continue;
    }
    const 銀兩花費 = Math.floor(30 * Math.pow(等級 + 1, 1.5));
    const 材料花費 = 等級 + 1;
    行.push(`${名稱}（目前 +${等級}） → 下一級需 ${銀兩花費} 銀兩 + ${材料花費} 強化石`);
  }
  return 行.join('\n');
}

function 強化裝備(c, 名稱) {
  if (!(c.已購裝備 || []).includes(名稱)) {
    return `你尚未擁有「${名稱}」，無法強化。`;
  }
  if (!c.裝備強化) c.裝備強化 = {};
  const 等級 = c.裝備強化[名稱] || 0;
  if (等級 >= 強化上限) {
    return `「${名稱}」已強化至 +${強化上限}，已達上限。`;
  }
  const 銀兩花費 = Math.floor(30 * Math.pow(等級 + 1, 1.5));
  const 材料花費 = 等級 + 1;
  if (c.銀兩 < 銀兩花費) {
    return `銀兩不足，強化「${名稱}」需要 ${銀兩花費} 銀兩，你目前只有 ${c.銀兩} 銀兩。`;
  }
  if ((c.強化石 || 0) < 材料花費) {
    return `強化石不足，強化「${名稱}」需要 ${材料花費} 顆強化石，你目前只有 ${c.強化石 || 0} 顆。`;
  }
  c.銀兩 -= 銀兩花費;
  c.強化石 -= 材料花費;
  c.裝備強化[名稱] = 等級 + 1;
  return `花費 ${銀兩花費} 銀兩、${材料花費} 顆強化石，將「${名稱}」強化至 +${等級 + 1}！`;
}

